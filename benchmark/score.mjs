#!/usr/bin/env node
// Scores a moderation system against a labeled corpus and writes a Markdown
// report. Exits non-zero if any item fails that is NOT flagged documented_miss
// — so this doubles as a regression ratchet in CI.
//
//   node benchmark/score.mjs
//   node benchmark/score.mjs --adapter benchmark/adapters/other.mjs
//   node benchmark/score.mjs --json
//   node benchmark/score.mjs --out benchmark/results/open-v0.1.md

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const CONTEXTS = ["first_person", "third_party", "topic_mention", null];

function parseArgs(argv) {
  const args = {
    corpus: "benchmark/data/open-v0.1.jsonl",
    adapter: "benchmark/adapters/lexicon-middleware.mjs",
    out: null,
    json: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--json") args.json = true;
    else if (a === "--corpus") args.corpus = argv[++i];
    else if (a === "--adapter") args.adapter = argv[++i];
    else if (a === "--out") args.out = argv[++i];
    else if (a === "--help" || a === "-h") {
      console.log("usage: node benchmark/score.mjs [--corpus F] [--adapter F] [--out F] [--json]");
      process.exit(0);
    } else {
      console.error(`unknown argument: ${a}`);
      process.exit(2);
    }
  }
  return args;
}

function loadCorpus(file) {
  const lines = readFileSync(file, "utf8").split("\n");
  const items = [];
  lines.forEach((line, i) => {
    const trimmed = line.trim();
    if (!trimmed) return;
    try {
      items.push(JSON.parse(trimmed));
    } catch (err) {
      throw new Error(`${file}:${i + 1}: ${err.message}`);
    }
  });
  const seen = new Set();
  for (const item of items) {
    if (seen.has(item.id)) throw new Error(`duplicate id: ${item.id}`);
    seen.add(item.id);
  }
  return items;
}

function pct(n, d) {
  if (d === 0) return "n/a";
  return `${((n / d) * 100).toFixed(0)}% (${n}/${d})`;
}

async function run() {
  const args = parseArgs(process.argv.slice(2));
  const adapter = await import(pathToFileURL(path.resolve(args.adapter)).href);
  const items = loadCorpus(args.corpus);

  const results = [];
  for (const item of items) {
    const got = await adapter.classify(item.text);

    const actionOk = got.action === item.expect_action;
    const severityOk = got.severity === item.expect_severity;
    const contextOk =
      got.crisis_context === undefined ? null : (got.crisis_context ?? null) === (item.expect_context ?? null);
    const piiOk = item.expect_pii === undefined ? null : Boolean(got.pii) === item.expect_pii;

    // An item passes on the decision the deployment actually acts on: the
    // action, its severity, and — where the corpus asserts it — the PII flag.
    // crisis_context is reported separately: a system with no such notion is
    // scored on behavior, not on vocabulary it never claimed to have.
    const pass = actionOk && severityOk && piiOk !== false;

    results.push({ item, got, actionOk, severityOk, contextOk, piiOk, pass });
  }

  const report = buildReport(results, adapter, args);
  const regressions = results.filter((r) => !r.pass && !r.item.documented_miss && !r.item.open_defect);

  if (args.json) {
    console.log(JSON.stringify({ adapter: adapter.name, results, regressions: regressions.length }, null, 2));
  } else if (args.out) {
    writeFileSync(args.out, report);
    console.log(`wrote ${args.out}`);
  } else {
    console.log(report);
  }

  if (regressions.length) {
    console.error(`\n${regressions.length} regression(s) — items failing that are not documented gaps:`);
    for (const r of regressions) {
      console.error(
        `  ${r.item.id}  ${JSON.stringify(r.item.text)}\n` +
          `      expected ${r.item.expect_action}/${r.item.expect_severity}, got ${r.got.action}/${r.got.severity}`
      );
    }
    process.exit(1);
  }
}

function buildReport(results, adapter, args) {
  const L = [];
  const byCategory = new Map();
  for (const r of results) {
    if (!byCategory.has(r.item.category)) byCategory.set(r.item.category, []);
    byCategory.get(r.item.category).push(r);
  }

  L.push(`# Benchmark results — ${adapter.name}`);
  L.push("");
  L.push(adapter.description ?? "");
  L.push("");
  L.push(`Corpus: \`${args.corpus}\` · ${results.length} items · generated by \`benchmark/score.mjs\``);
  L.push("");
  L.push("<!-- Generated file. Regenerate with: npm run benchmark -->");
  L.push("");

  // Headline: recall on messages where someone is actually at risk.
  const atRisk = results.filter(
    (r) => r.item.expect_context === "first_person" || r.item.expect_context === "third_party"
  );
  const atRiskCaught = atRisk.filter((r) => r.got.action === "escalate");
  const fp = results.filter((r) => r.item.category === "first_person_explicit" || r.item.category === "first_person_indirect");
  const fpCaught = fp.filter((r) => r.got.action === "escalate");
  const fpExplicit = results.filter((r) => r.item.category === "first_person_explicit");
  const fpIndirect = results.filter((r) => r.item.category === "first_person_indirect");

  L.push("## Headline");
  L.push("");
  L.push("| measure | result |");
  L.push("|---|---|");
  L.push(`| Escalation recall, anyone at risk | ${pct(atRiskCaught.length, atRisk.length)} |`);
  L.push(`| Escalation recall, first-person disclosures | ${pct(fpCaught.length, fp.length)} |`);
  L.push(`| — of those, explicitly phrased | ${pct(fpExplicit.filter((r) => r.got.action === "escalate").length, fpExplicit.length)} |`);
  L.push(`| — of those, indirectly phrased | ${pct(fpIndirect.filter((r) => r.got.action === "escalate").length, fpIndirect.length)} |`);
  const controls = results.filter((r) => r.item.category === "benign_control");
  const controlFP = controls.filter((r) => r.got.action !== "allow" || r.got.severity !== "none");
  L.push(`| False-positive rate on benign controls | ${pct(controlFP.length, controls.length)} |`);
  L.push("");
  L.push(
    "The split between explicit and indirect is the number that matters. A detector that only " +
      "catches explicit phrasings catches the disclosures that were already easy to see."
  );
  L.push("");

  // Per-category agreement.
  L.push("## By category");
  L.push("");
  L.push("| category | items | correct action+severity | known gaps | open defects | regressions |");
  L.push("|---|---|---|---|---|---|");
  for (const [category, rs] of byCategory) {
    const passing = rs.filter((r) => r.pass).length;
    const gaps = rs.filter((r) => !r.pass && r.item.documented_miss).length;
    const open = rs.filter((r) => !r.pass && r.item.open_defect).length;
    const regs = rs.filter((r) => !r.pass && !r.item.documented_miss && !r.item.open_defect).length;
    L.push(`| \`${category}\` | ${rs.length} | ${pct(passing, rs.length)} | ${gaps} | ${open} | ${regs} |`);
  }
  L.push("");

  // Context confusion matrix.
  const reportsContext = results.some((r) => r.got.crisis_context !== undefined);
  if (reportsContext) {
    L.push("## Crisis-context confusion");
    L.push("");
    L.push("Rows are ground truth, columns are what the system returned.");
    L.push("");
    const label = (c) => (c === null ? "_none_" : `\`${c}\``);
    L.push(`| truth \\ returned | ${CONTEXTS.map(label).join(" | ")} |`);
    L.push(`|---|${CONTEXTS.map(() => "---").join("|")}|`);
    for (const truth of CONTEXTS) {
      const row = results.filter((r) => (r.item.expect_context ?? null) === truth);
      const cells = CONTEXTS.map((got) => {
        const n = row.filter((r) => (r.got.crisis_context ?? null) === got).length;
        return truth === got ? (n ? `**${n}**` : "·") : n || "·";
      });
      L.push(`| ${label(truth)} | ${cells.join(" | ")} |`);
    }
    L.push("");
  }

  // PII.
  const piiItems = results.filter((r) => r.item.expect_pii !== undefined);
  if (piiItems.length) {
    const truePos = piiItems.filter((r) => r.item.expect_pii && r.got.pii).length;
    const falsePos = piiItems.filter((r) => !r.item.expect_pii && r.got.pii).length;
    const falseNeg = piiItems.filter((r) => r.item.expect_pii && !r.got.pii).length;
    L.push("## PII detection");
    L.push("");
    L.push(`Detected ${truePos} of ${truePos + falseNeg} real, with ${falsePos} false positive(s) on ${piiItems.length - truePos - falseNeg} non-PII item(s).`);
    L.push("");
  }

  // Gaps, open defects, and regressions, itemized.
  const gaps = results.filter((r) => !r.pass && r.item.documented_miss);
  const openDefects = results.filter((r) => !r.pass && r.item.open_defect);
  const regressions = results.filter((r) => !r.pass && !r.item.documented_miss && !r.item.open_defect);
  const closed = results.filter((r) => r.pass && (r.item.documented_miss || r.item.open_defect));

  L.push("## Known gaps");
  L.push("");
  if (!gaps.length) L.push("_None._");
  else {
    L.push("Documented limitations. Expected to fail; they do not fail CI.");
    L.push("");
    L.push("| id | message | expected | got | why |");
    L.push("|---|---|---|---|---|");
    for (const r of gaps) {
      L.push(
        `| \`${r.item.id}\` | ${md(r.item.text)} | ${r.item.expect_action}/${r.item.expect_severity} | ` +
          `${r.got.action}/${r.got.severity} | ${md(r.item.note ?? "")} |`
      );
    }
  }
  L.push("");

  L.push("## Open defects");
  L.push("");
  if (!openDefects.length) L.push("_None._");
  else {
    L.push(
      "Not design limitations — things that are simply wrong, characterized but not yet fixed. " +
        "They do not fail CI so the ratchet stays usable, but every one of them is a bug with an owner."
    );
    L.push("");
    L.push("| id | defect | message | expected | got | why |");
    L.push("|---|---|---|---|---|---|");
    for (const r of openDefects) {
      L.push(
        `| \`${r.item.id}\` | \`${r.item.open_defect}\` | ${md(r.item.text)} | ` +
          `${r.item.expect_action}/${r.item.expect_severity} | ${r.got.action}/${r.got.severity} | ${md(r.item.note ?? "")} |`
      );
    }
  }
  L.push("");

  L.push("## Regressions");
  L.push("");
  if (!regressions.length) {
    L.push("_None._ Every item outside the documented gaps behaves as the corpus requires.");
  } else {
    L.push("| id | message | expected | got |");
    L.push("|---|---|---|---|");
    for (const r of regressions) {
      L.push(
        `| \`${r.item.id}\` | ${md(r.item.text)} | ${r.item.expect_action}/${r.item.expect_severity} | ` +
          `${r.got.action}/${r.got.severity} |`
      );
    }
  }
  L.push("");

  if (closed.length) {
    L.push("## Gaps now closed");
    L.push("");
    L.push("Flagged `documented_miss` or `open_defect` but passing. Remove the flag, and the README line it refers to.");
    L.push("");
    for (const r of closed) L.push(`- \`${r.item.id}\` — ${md(r.item.text)}`);
    L.push("");
  }

  return L.join("\n");
}

function md(s) {
  return String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
}

run().catch((err) => {
  console.error(err);
  process.exit(2);
});
